/**
 * Third-party licence inventory (Phase 11 S3). Reads the packages recorded in `<dist>/build-info.json` (what the build
 * actually bundled into `cli.mjs` and `web/app.js`), and for each one its declared licence and licence file from
 * `node_modules`. Writes `THIRD_PARTY_LICENSES.md` (full texts; shipped in the package and kept in the repository).
 * The build calls `writeThirdPartyLicenses`; run alone it regenerates the repository copy:
 *
 *   npx tsx scripts/licenses.ts [dist]      (after `npm run build`)
 *
 * Exit 1 (or a thrown error from the build) when a bundled package's licence is not on the allow list or unknown.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Licences compatible with distributing Synaptome under Apache-2.0 (permissive; notices kept).
export const ALLOWED_LICENCES = ['MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'BlueOak-1.0.0', 'CC0-1.0', 'Unlicense'];

export interface LicenceEntry { name: string; version: string; license: string; where: string[]; text: string | null; author: string | null; repository: string | null }

export function licenceInventory(info: { bundledPackages: Record<string, number>; webBundledPackages?: Record<string, number> }): LicenceEntry[] {
  const entries = new Map<string, LicenceEntry>();
  for (const [where, list] of [['cli.mjs', info.bundledPackages], ['web/app.js', info.webBundledPackages ?? {}]] as const) {
    for (const name of Object.keys(list)) {
      const e = entries.get(name);
      if (e) {
        e.where.push(where);
        continue;
      }
      const dir = path.join(root, 'node_modules', name);
      const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
      const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l: any) => l.type).join(' OR ') : 'UNKNOWN');
      const file = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|-|$)/i.test(f));
      const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name ?? null;
      const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? null;
      entries.set(name, { name, version: pkg.version, license, where: [where], text: file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : null, author, repository });
    }
  }
  return [...entries.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/** Writes the inventory as markdown to `outFile`; returns the summary. Throws when a licence is not allowed. */
export function writeThirdPartyLicenses(dist: string, outFile: string) {
  const info = JSON.parse(fs.readFileSync(path.join(dist, 'build-info.json'), 'utf8'));
  const list = licenceInventory(info);
  const notAllowed = list.filter((e) => !e.license.split(/\s+OR\s+|[()]/).some((l) => ALLOWED_LICENCES.includes(l.trim())));
  const counts: Record<string, number> = {};
  for (const e of list) counts[e.license] = (counts[e.license] ?? 0) + 1;
  const doc = [
    '# Third-party licences',
    '',
    `Packages bundled into the Synaptome ${info.version} distribution (\`cli.mjs\` and \`web/app.js\`), as recorded by the`,
    'build. Generated by `scripts/licenses.ts`; do not edit by hand.',
    '',
    `${list.length} packages: ${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ')}.`,
    '',
    '| Package | Version | Licence | Bundled in | Licence text |',
    '|---|---|---|---|---|',
    ...list.map((e) => `| ${e.name} | ${e.version} | ${e.license} | ${e.where.join(', ')} | ${e.text ? 'below' : `not shipped by the package; ${e.license} per its package.json${e.author ? `, author ${e.author}` : ''}${e.repository ? `, ${e.repository.replace(/^git\+/, '')}` : ''}`} |`),
    '',
    ...list.filter((e) => e.text).flatMap((e) => [`## ${e.name} ${e.version} (${e.license})`, '', '```', e.text!, '```', '']),
  ].join('\n');
  fs.writeFileSync(outFile, doc);
  const summary = { packages: list.length, counts, withoutText: list.filter((e) => !e.text).map((e) => e.name), notAllowed: notAllowed.map((e) => `${e.name} (${e.license})`) };
  if (notAllowed.length) throw new Error(`Bundled package licence not allowed or unknown: ${summary.notAllowed.join(', ')}`);
  return summary;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const s = writeThirdPartyLicenses(path.resolve(process.argv[2] ?? path.join(root, 'dist')), path.join(root, 'THIRD_PARTY_LICENSES.md'));
    process.stdout.write(`${s.packages} bundled packages: ${JSON.stringify(s.counts)}; without a licence file: ${s.withoutText.join(', ') || 'none'}\n`);
  } catch (e: any) {
    process.stdout.write(`${e.message}\n`);
    process.exitCode = 1;
  }
}
